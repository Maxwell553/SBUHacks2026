// Rasterises Natural Earth land polygons (world-atlas, 50m) into a 1° bitmask
// used to colour the low-poly globe in video map scenes. Uses an even-odd
// scanline fill in lon/lat space (the dataset is already split at ±180°).
// Usage: npm run landmask
import { readFileSync, writeFileSync } from "node:fs";
import { feature } from "topojson-client";

const topo = JSON.parse(readFileSync("node_modules/world-atlas/land-50m.json", "utf8"));
const land = feature(topo, topo.objects.land);

const W = 360,
  H = 180;

// Make longitudes continuous; rings that wrap the globe enclose a pole and
// are closed along it.
function unwrap(ring) {
  const out = [[ring[0][0], ring[0][1]]];
  for (let i = 1; i < ring.length; i++) {
    let [x, y] = ring[i];
    const px = out[i - 1][0];
    while (x - px > 180) x -= 360;
    while (x - px < -180) x += 360;
    out.push([x, y]);
  }
  const drift = out[out.length - 1][0] - out[0][0];
  if (Math.abs(drift) > 180) {
    const meanLat = out.reduce((a, p) => a + p[1], 0) / out.length;
    const pole = meanLat < 0 ? -90 : 90;
    out.push([out[out.length - 1][0], pole], [out[0][0], pole]);
  }
  return out;
}

const rings = [];
for (const f of land.features) {
  const g = f.geometry;
  const polys = g.type === "Polygon" ? [g.coordinates] : g.coordinates;
  for (const poly of polys) for (const ring of poly) rings.push(unwrap(ring));
}

const bits = new Uint8Array(W * H);
for (let y = 0; y < H; y++) {
  const lat = 89.5 - y;
  for (const ring of rings) {
    const xs = [];
    for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
      const [x1, y1] = ring[i];
      const [x2, y2] = ring[j];
      if (y1 > lat !== y2 > lat) xs.push(x1 + ((lat - y1) / (y2 - y1)) * (x2 - x1));
    }
    xs.sort((a, b) => a - b);
    for (let k = 0; k + 1 < xs.length; k += 2) {
      const c0 = Math.ceil(xs[k] + 179.5);
      const c1 = Math.floor(xs[k + 1] + 179.5);
      for (let c = c0; c <= c1; c++) bits[y * W + (((c % W) + W) % W)] ^= 1;
    }
  }
}

const bytes = new Uint8Array((W * H) / 8);
let count = 0;
for (let i = 0; i < W * H; i++) {
  if (bits[i]) {
    bytes[i >> 3] |= 1 << (i & 7);
    count++;
  }
}
const b64 = Buffer.from(bytes).toString("base64");
writeFileSync(
  "lib/lowpoly/landmask.ts",
  `// Generated by scripts/assets/build-landmask.mjs from Natural Earth (public domain).\n` +
    `// 360x180 bitmask, row 0 = 89.5°N, column 0 = 179.5°W.\n` +
    `export const LANDMASK_W = ${W};\nexport const LANDMASK_H = ${H};\n` +
    `export const LANDMASK_B64 =\n  "${b64}";\n`,
);
console.log(`land cells: ${count} / ${W * H} (${((count / (W * H)) * 100).toFixed(1)}%)`);

// Coarse ASCII preview for sanity checking.
let preview = "";
for (let y = 0; y < H; y += 6) {
  let row = "";
  for (let x = 0; x < W; x += 3) row += bits[y * W + x] ? "#" : ".";
  preview += row + "\n";
}
console.log(preview);
